#!/usr/bin/env python3
"""
export_forms.py — turn the SESC-FRM record capture schemas into one Apps Script file.

Run from the repository root:   python3 build/workspace_forms/export_forms.py
Writes:                          out/workspace-forms/SESC-Record-Forms.gs   (gitignored)

That one file is pasted into a Google Apps Script project owned by the SESC Workspace
account and run once. It holds the form definitions, generated from forms/*.yaml, followed
by build/workspace_forms/Code.gs. See build/workspace_forms/README.md.

Why generated, not hand-built (decision D15): the field KEYS in forms/*.yaml are the names
the records will carry when they move to the SESC Platform. A hand-built Google Form keeps
only the labels, and a label is edited the first time someone tidies the wording. The
generated form carries a _field_map sheet tying every column back to its key.

The YAML is the source. Never edit the generated .gs by hand — change the YAML, re-export.
"""
import glob, json, os, sys, datetime
try:
    import yaml
except ImportError:
    sys.exit("export_forms.py needs PyYAML:  pip install pyyaml")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "out", "workspace-forms")
TYPES = {"date", "time", "text", "textarea", "select", "multiselect", "number", "file"}


def load():
    defs, problems = [], []
    for path in sorted(glob.glob(os.path.join(ROOT, "forms", "SESC-FRM-*.yaml"))):
        d = yaml.safe_load(open(path, encoding="utf-8"))
        rel = os.path.relpath(path, ROOT)
        keys = set()
        for f in d.get("fields", []):
            if f["type"] not in TYPES:
                problems.append(f"{rel}: field '{f['key']}' has unknown type '{f['type']}'")
            if f["key"] in keys:
                problems.append(f"{rel}: field key '{f['key']}' used twice")
            keys.add(f["key"])
            if f["type"] in ("select", "multiselect") and not f.get("options"):
                problems.append(f"{rel}: field '{f['key']}' is a {f['type']} with no options")
        if "correction_of" not in keys:
            problems.append(f"{rel}: no correction_of field — records must be append-only (D15)")
        defs.append({
            "id": d["id"],
            "title": d["title"],
            "version": str(d["version"]),
            "status": d["status"],
            "owner": d["owner"],
            "source": rel,
            "clauses": d.get("clauses") or {},
            "purpose": " ".join(str(d.get("purpose", "")).split()),
            "guidance": d.get("guidance") or [],
            "fields": [{
                "key": f["key"],
                "label": f["label"],
                "type": f["type"],
                "required": bool(f.get("required")),
                "help": " ".join(str(f.get("help", "")).split()),
                "options": [str(o) for o in (f.get("options") or [])],
            } for f in d["fields"]],
        })
    return defs, problems


def main():
    defs, problems = load()
    if problems:
        print("\n".join(problems))
        sys.exit("\nEXPORT FAILS. Fix the schema problems above.")
    code = open(os.path.join(HERE, "Code.gs"), encoding="utf-8").read()
    os.makedirs(OUT, exist_ok=True)
    stamp = datetime.date.today().isoformat()
    head = ("// GENERATED by build/workspace_forms/export_forms.py on " + stamp + ".\n"
            "// DO NOT EDIT. Source: forms/SESC-FRM-*.yaml and build/workspace_forms/Code.gs.\n\n"
            "const FORM_DEFS = " + json.dumps(defs, indent=1, ensure_ascii=False) + ";\n\n")
    path = os.path.join(OUT, "SESC-Record-Forms.gs")
    open(path, "w", encoding="utf-8").write(head + code)
    print(f"Wrote {os.path.relpath(path, ROOT)} — {len(defs)} forms:")
    for d in defs:
        files = [f["key"] for f in d["fields"] if f["type"] == "file"]
        print(f"  {d['id']} v{d['version']}  {d['title']}  ({len(d['fields'])} fields"
              + (f"; file field(s) {files} need adding by hand" if files else "") + ")")


if __name__ == "__main__":
    main()
